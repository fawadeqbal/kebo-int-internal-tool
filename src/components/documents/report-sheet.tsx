import type { ReactNode } from "react";
import type { AppSettings } from "@/modules/settings/service";
import { cn } from "@/lib/utils/cn";

/**
 * A printed report (list exports and the Reports page). Built for paper:
 * letterhead, title, what was included, key figures, then the table. The PDF
 * download prints this page with Chrome; table headers repeat on every page
 * and the page footer carries "Page x of y".
 */

export const reportLabel = "text-[9px] font-semibold tracking-[0.14em] text-stone-500 uppercase";

export function ReportSheet({
  settings,
  title,
  kind = "Report",
  period,
  filters,
  generatedAt,
  generatedBy,
  records,
  note,
  landscape,
  kpis,
  children,
}: {
  settings: AppSettings;
  title: string;
  kind?: string;
  /** e.g. "01 Oct 2026 – 24 Oct 2026" */
  period?: string;
  filters?: string;
  generatedAt: string;
  generatedBy: string;
  records?: string;
  /** e.g. "Showing the first 2,000 of 2,345 rows." */
  note?: string;
  landscape?: boolean;
  kpis?: { label: string; value: ReactNode; hint?: ReactNode; tone?: "bad" | "ok" }[];
  children: ReactNode;
}) {
  return (
    <article
      className={cn(
        "mx-auto w-full bg-white p-8 text-[11px] leading-normal text-stone-800 [print-color-adjust:exact] print:p-0",
        landscape ? "max-w-[297mm]" : "max-w-[210mm]",
      )}
    >
      {/* Wide registers print across the page (also when printed from the browser). */}
      {landscape && <style>{"@page { size: A4 landscape; margin: 14mm 12mm; }"}</style>}
      <header className="flex items-start justify-between gap-6">
        <div className="flex min-w-0 items-start gap-2.5">
          <span className="mt-0.5 flex size-8 shrink-0 items-center justify-center rounded bg-stone-900 text-white" aria-hidden>
            <svg viewBox="0 0 32 32" className="size-4">
              <path d="M8 10h16M8 16h11M8 22h7" stroke="currentColor" strokeWidth="2.75" strokeLinecap="round" />
            </svg>
          </span>
          <div>
            <p className="text-[13px] leading-tight font-bold text-stone-900">{settings.companyName}</p>
            <p className="text-stone-500">{[settings.companyAddress.split("\n")[0], settings.companyPhone, settings.companyEmail].filter(Boolean).join("  ·  ")}</p>
          </div>
        </div>
        <div className="shrink-0 text-right whitespace-nowrap">
          <p className={reportLabel}>{kind}</p>
          <p className="text-[20px] leading-tight font-semibold tracking-tight text-stone-900">{title}</p>
          {period && <p className="mt-0.5 font-medium text-stone-700">{period}</p>}
        </div>
      </header>
      <div className="mt-4 h-[2px] bg-stone-900" />

      <dl className={cn("mt-3 grid gap-x-6 gap-y-1.5 border-b border-stone-200 pb-3", landscape ? "grid-cols-[auto_auto_auto_1fr]" : "grid-cols-[auto_auto_1fr]")}>
        <div>
          <dt className={reportLabel}>Generated</dt>
          <dd className="font-medium text-stone-900">{generatedAt}</dd>
        </div>
        <div>
          <dt className={reportLabel}>By</dt>
          <dd className="font-medium text-stone-900">{generatedBy}</dd>
        </div>
        {records && (
          <div>
            <dt className={reportLabel}>Records</dt>
            <dd className="font-medium text-stone-900 tabular-nums">{records}</dd>
          </div>
        )}
        {filters && (
          <div className={cn(!landscape && "col-span-full")}>
            <dt className={reportLabel}>Included</dt>
            <dd className="text-stone-700">{filters}</dd>
          </div>
        )}
      </dl>
      {note && <p className="mt-2 rounded bg-amber-50 px-2.5 py-1.5 text-amber-900">{note}</p>}

      {kpis && kpis.length > 0 && (
        <section className={cn("mt-4 grid gap-2.5", kpis.length >= 5 ? "grid-cols-5" : kpis.length === 4 ? "grid-cols-4" : "grid-cols-3")}>
          {kpis.map((k) => (
            <div key={k.label} className="rounded border border-stone-200 px-3 py-2">
              <p className={reportLabel}>{k.label}</p>
              <p className={cn("mt-0.5 text-[15px] font-semibold text-stone-900 tabular-nums", k.tone === "bad" && "text-red-700", k.tone === "ok" && "text-emerald-700")}>{k.value}</p>
              {k.hint && <p className="text-[10px] text-stone-500">{k.hint}</p>}
            </div>
          ))}
        </section>
      )}

      <div className="mt-4 space-y-5">{children}</div>

      <p className="mt-6 border-t border-stone-200 pt-2 text-center text-[9.5px] text-stone-400">
        {settings.companyName} · internal report · generated by Kebo RFQ Desk
      </p>
    </article>
  );
}

export interface ReportColumn {
  header: string;
  align?: "left" | "right" | "center";
  className?: string;
}

/** A report table: dark header row (repeats on each printed page), light zebra rows, optional totals row. */
export function ReportTable({ columns, rows, footer, empty = "Nothing to show." }: { columns: ReportColumn[]; rows: ReactNode[][]; footer?: ReactNode[]; empty?: string }) {
  const align = (a?: ReportColumn["align"]) => (a === "right" ? "text-right" : a === "center" ? "text-center" : "text-left");
  return (
    <table className="w-full border-collapse">
      <thead>
        <tr className="bg-stone-900 text-white">
          {columns.map((c) => (
            <th key={c.header} className={cn("px-2 py-1.5 text-[8.5px] font-semibold tracking-[0.08em] uppercase first:pl-2.5 last:pr-2.5", align(c.align), c.className)}>
              {c.header}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.length === 0 ? (
          <tr>
            <td colSpan={columns.length} className="px-2.5 py-6 text-center text-stone-500">
              {empty}
            </td>
          </tr>
        ) : (
          rows.map((cells, i) => (
            <tr key={i} className="border-b border-stone-200 align-top even:bg-stone-50">
              {cells.map((cell, j) => (
                <td key={j} className={cn("px-2 py-1 first:pl-2.5 last:pr-2.5", align(columns[j]?.align), columns[j]?.align === "right" && "tabular-nums whitespace-nowrap", columns[j]?.className)}>
                  {cell}
                </td>
              ))}
            </tr>
          ))
        )}
      </tbody>
      {footer && rows.length > 0 && (
        <tfoot className="[display:table-row-group]">
          <tr className="border-t-2 border-stone-900 font-semibold text-stone-900">
            {footer.map((cell, j) => (
              <td key={j} className={cn("px-2 py-2 first:pl-2.5 last:pr-2.5", align(columns[j]?.align), columns[j]?.align === "right" && "tabular-nums whitespace-nowrap")}>
                {cell}
              </td>
            ))}
          </tr>
        </tfoot>
      )}
    </table>
  );
}

export function ReportSection({ title, description, children, className }: { title: string; description?: string; children: ReactNode; className?: string }) {
  return (
    <section className={cn("break-inside-avoid-page", className)}>
      <div className="mb-1.5 flex items-baseline justify-between gap-3">
        <h2 className="text-[12px] font-semibold text-stone-900">{title}</h2>
        {description && <p className="text-[10px] text-stone-500">{description}</p>}
      </div>
      {children}
    </section>
  );
}

/** Two-line cell: main text and a small grey line under it. */
export function Cell({ main, sub, mono }: { main: ReactNode; sub?: ReactNode; mono?: boolean }) {
  return (
    <>
      <span className={cn("block text-stone-900", mono && "font-mono text-[10px]")}>{main}</span>
      {sub && <span className="block text-[9.5px] text-stone-500">{sub}</span>}
    </>
  );
}

/** A thin bar for inline charts in tables. */
export function Bar({ value, max, className }: { value: number; max: number; className?: string }) {
  return (
    <span className="block h-1.5 w-full rounded-full bg-stone-200">
      <span className={cn("block h-1.5 rounded-full bg-stone-800", className)} style={{ width: `${max > 0 ? Math.max(value > 0 ? 3 : 0, (value / max) * 100) : 0}%` }} />
    </span>
  );
}
