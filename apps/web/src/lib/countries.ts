const NAMES = new Map<string, string>(COUNTRIES.map(([c, n]) => [c, n]));

export const isUnknownCountry = (code: string | null | undefined) => !code || code === UNKNOWN_COUNTRY;

/** "Nigeria"; "Not known yet" for ZZ; the bare code for anything not in the list. */
export function countryName(code: string | null | undefined): string {
  if (isUnknownCountry(code)) return "Not known yet";
  return NAMES.get(code!) ?? code!;
}
