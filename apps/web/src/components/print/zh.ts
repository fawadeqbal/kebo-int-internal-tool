const key = (t: string) =>
  t
    .replace(/\s*:\s*$/, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();

/** The Chinese for a label the papers print, or null (then it prints in English only). */
export function zhOf(text: string): string | null {
  const k = key(text);
  if (ZH[k]) return ZH[k];
  // "Total CFR Karachi Port", "Total FOB Price": the total, priced or not.
  if (/^total\b/.test(k)) return /\bprice\b/.test(k) ? "总价" : "合计";
  return null;
}
