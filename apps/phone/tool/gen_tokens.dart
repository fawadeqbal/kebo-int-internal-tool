// Writes lib/design/tokens.g.dart from design/kestrel.tokens.json (the Kestrel design system).
//
//   dart run tool/gen_tokens.dart          write the file
//   dart run tool/gen_tokens.dart --check  fail (exit 1) when the file is out of date (CI)
import 'dart:convert';
import 'dart:io';

const _src = 'design/kestrel.tokens.json';
const _out = 'lib/design/tokens.g.dart';

void main(List<String> args) {
  final json = jsonDecode(File(_src).readAsStringSync()) as Map<String, dynamic>;
  final code = generate(json);
  final out = File(_out);
  if (args.contains('--check')) {
    if (!out.existsSync() || out.readAsStringSync() != code) {
      stderr.writeln('$_out is out of date: run `dart run tool/gen_tokens.dart`.');
      exit(1);
    }
    stdout.writeln('$_out is up to date.');
    return;
  }
  out.writeAsStringSync(code);
  stdout.writeln('Wrote $_out');
}

String camel(String name) {
  final parts = name.split(RegExp(r'[-.]'));
  return parts.first + parts.skip(1).map((p) => p.isEmpty ? p : p[0].toUpperCase() + p.substring(1)).join();
}

/// '#rrggbb', '#rgb', '#rrggbbaa' or 'rgba(r, g, b, a)' → 0xAARRGGBB.
int parseColor(String v) {
  v = v.trim();
  if (v.startsWith('#')) {
    var h = v.substring(1);
    if (h.length == 3) h = h.split('').map((c) => '$c$c').join();
    if (h.length == 6) h = '${h}ff';
    final rgb = h.substring(0, 6), a = h.substring(6, 8);
    return int.parse('$a$rgb', radix: 16);
  }
  final m = RegExp(r'rgba?\(([^)]*)\)').firstMatch(v);
  if (m == null) throw FormatException('Unsupported colour: $v');
  final n = m.group(1)!.split(',').map((s) => s.trim()).toList();
  final r = int.parse(n[0]), g = int.parse(n[1]), b = int.parse(n[2]);
  final a = n.length > 3 ? (double.parse(n[3]) * 255).round() : 255;
  return (a << 24) | (r << 16) | (g << 8) | b;
}

String hex(int c) => '0x${c.toRadixString(16).padLeft(8, '0').toUpperCase()}';

double px(String v) => double.parse(v.replaceAll('px', ''));

String generate(Map<String, dynamic> t) {
  final color = t['color'] as Map<String, dynamic>;
  final themes = (color['themes'] as List).map((e) => (e as Map)['id'] as String).toList();
  final tokens = (color['tokens'] as List).cast<Map<String, dynamic>>();
  final primitive = <String, int>{};
  final semantic = <Map<String, dynamic>>[];
  for (final tok in tokens) {
    if (tok['value'] is String) {
      primitive[tok['name'] as String] = parseColor(tok['value'] as String);
    } else {
      semantic.add(tok);
    }
  }
  int resolve(String v) {
    final m = RegExp(r'^\{(.+)\}$').firstMatch(v);
    if (m != null) {
      final ref = primitive[m.group(1)!];
      if (ref == null) throw FormatException('Unknown token ${m.group(1)}');
      return ref;
    }
    return parseColor(v);
  }

  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from design/kestrel.tokens.json. Do not edit.')
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln()
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln()
    ..writeln('/// Raw palette. Components never use these: they read [KColors].')
    ..writeln('abstract final class KPalette {');
  primitive.forEach((k, v) => b.writeln('  static const ${camel(k)} = Color(${hex(v)});'));
  b.writeln('}\n');

  // Semantic colours + shadows, per theme, as a ThemeExtension.
  final shadows = ((t['shadow'] as Map)['tokens'] as List).cast<Map<String, dynamic>>();
  b.writeln('/// Semantic colours and elevation for one theme. Read with `context.k` (see theme.dart).');
  b.writeln('@immutable');
  b.writeln('class KColors extends ThemeExtension<KColors> {');
  b.writeln('  const KColors({');
  for (final s in semantic) {
    b.writeln('    required this.${camel(s['name'] as String)},');
  }
  for (final s in shadows) {
    b.writeln('    required this.${camel(s['name'] as String)},');
  }
  b.writeln('  });\n');
  for (final s in semantic) {
    b.writeln('  /// ${(s['usage'] as String? ?? '').replaceAll('\n', ' ')}');
    b.writeln('  final Color ${camel(s['name'] as String)};');
  }
  for (final s in shadows) {
    b.writeln('  /// ${(s['usage'] as String? ?? '')}');
    b.writeln('  final List<BoxShadow> ${camel(s['name'] as String)};');
  }
  String shadowList(String css) {
    // e.g. "0 1px 2px rgba(...), 0 1px 3px rgba(...)"
    final parts = <String>[];
    for (final m in RegExp(
      r'(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(rgba?\([^)]*\)|#[0-9a-fA-F]+)',
    ).allMatches(css)) {
      parts.add(
        'BoxShadow(offset: Offset(${px(m.group(1)!)}, ${px(m.group(2)!)}), blurRadius: ${px(m.group(3)!)}, color: Color(${hex(parseColor(m.group(4)!))}))',
      );
    }
    return '[${parts.join(', ')}]';
  }

  for (final th in themes) {
    b.writeln('\n  static const $th = KColors(');
    for (final s in semantic) {
      final v = (s['value'] as Map)[th] ?? (s['value'] as Map)[themes.first];
      b.writeln('    ${camel(s['name'] as String)}: Color(${hex(resolve(v as String))}),');
    }
    for (final s in shadows) {
      final v = s['value'] is String
          ? s['value'] as String
          : ((s['value'] as Map)[th] ?? (s['value'] as Map)[themes.first]) as String;
      b.writeln('    ${camel(s['name'] as String)}: ${shadowList(v)},');
    }
    b.writeln('  );');
  }
  // copyWith / lerp (lerp snaps: themes switch, they do not blend).
  b.writeln('\n  @override');
  b.writeln('  KColors copyWith() => this;\n');
  b.writeln('  @override');
  b.writeln('  KColors lerp(covariant KColors? other, double t) => other == null || t < 0.5 ? this : other;');
  b.writeln('}\n');

  void lengths(String family, String cls, String doc) {
    b.writeln('/// $doc');
    b.writeln('abstract final class $cls {');
    for (final tok in ((t[family] as Map)['tokens'] as List).cast<Map<String, dynamic>>()) {
      final rest = camel((tok['name'] as String).replaceFirst(RegExp(r'^(space|radius|size|opacity)-'), ''));
      final id = RegExp(r'^\d').hasMatch(rest) ? 's$rest' : rest;
      b.writeln('  /// ${tok['usage'] ?? ''}');
      b.writeln('  static const double $id = ${px('${tok['value']}')};');
    }
    b.writeln('}\n');
  }

  lengths('spacing', 'KSpace', 'The 4-point grid: every margin, padding and gap.');
  lengths('radius', 'KRadius', 'Corner radii.');
  lengths('size', 'KSize', 'Touch targets, controls, icons and bars.');
  lengths('opacity', 'KOpacity', 'Opacities for disabled, pressed and hover states.');

  // Type scale.
  b.writeln('/// The type scale (Inter). Sizes follow the OS text-size setting.');
  b.writeln('abstract final class KType {');
  b.writeln("  static const family = 'Inter';");
  for (final g in ((t['type'] as Map)['groups'] as List).cast<Map<String, dynamic>>()) {
    for (final s in (g['styles'] as List).cast<Map<String, dynamic>>()) {
      final size = px(s['fontSize'] as String), lh = px(s['lineHeight'] as String);
      final w = s['fontWeight'] as int;
      final ls = s['letterSpacing'] as String?;
      final lsv = ls == null
          ? ''
          : ', letterSpacing: ${(double.parse(ls.replaceAll('em', '')) * size).toStringAsFixed(2)}';
      b.writeln('  /// ${s['usage']}');
      b.writeln(
        '  static const ${camel(s['name'] as String)} = TextStyle(fontFamily: family, fontSize: $size, height: ${(lh / size).toStringAsFixed(4)}, fontWeight: FontWeight.w$w$lsv);',
      );
    }
  }
  b.writeln('}');
  return b.toString();
}
